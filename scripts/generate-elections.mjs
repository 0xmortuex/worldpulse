/**
 * Generate `data/elections.json` — Phase C.4's election calendar.
 *
 * ## P298 is the expensive join, for the third time
 *
 * Four query shapes 504'd or 502'd before this one worked, and the cause was
 * not the date filter and not the endpoint:
 *
 * ```
 * trivial control                                    200    fast
 * COUNT elections + date filter                      200   4735ms   131 upcoming
 * elections + date + ?c wdt:P298 ?iso                502   49664ms
 * ```
 *
 * The date filter is affordable. **Attaching the ISO code is what dies** — and
 * that is the identical finding from `generate-armed-forces.mjs`, where
 * `?country wdt:P298 ?iso` took a 338-row query to a 65-second timeout.
 *
 * The fix is the same, so it is applied rather than rediscovered: two cheap
 * queries, joined in JavaScript, where a few hundred rows against a few hundred
 * costs nothing. **Three occurrences is a pattern worth naming** — see rule 48.
 *
 *   npx tsx scripts/generate-elections.mjs
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ENDPOINT = 'https://query.wikidata.org/sparql';
const HEADERS = {
  'User-Agent': 'worldpulse/0.0 (https://github.com/0xmortuex/worldpulse) elections',
  Accept: 'application/sparql-results+json',
  'Content-Type': 'application/sparql-query',
};

async function ask(label, query) {
  const res = await fetch(ENDPOINT, {
    method: 'POST',
    headers: HEADERS,
    body: query,
    signal: AbortSignal.timeout(90_000),
  });
  if (!res.ok) {
    console.error(`${label}: WDQS returned ${res.status} — nothing written`);
    process.exit(1);
  }
  return (await res.json()).results.bindings;
}

/**
 * A window rather than `NOW()`. A literal bound is a constraint the optimizer
 * can use; `NOW()` is computed per row, and the difference showed up as a
 * timeout.
 */
const FROM = new Date().toISOString().slice(0, 10);
const TO = new Date(Date.now() + 730 * 86_400_000).toISOString().slice(0, 10);

const elections = await ask(
  'elections',
  `SELECT ?e ?eLabel ?country ?date WHERE {
     ?e wdt:P31 wd:Q40231 .
     ?e wdt:P585 ?date .
     FILTER(?date >= "${FROM}T00:00:00Z"^^xsd:dateTime && ?date <= "${TO}T00:00:00Z"^^xsd:dateTime)
     ?e wdt:P17 ?country .
     SERVICE wikibase:label { bd:serviceParam wikibase:language "en" . }
   } LIMIT 400`,
);

const isoRows = await ask(
  'iso codes',
  'SELECT ?country ?iso WHERE { ?country wdt:P298 ?iso . }',
);

const isoByQid = new Map(isoRows.map((row) => [row.country.value, row.iso.value]));

const seen = new Set();
const entries = [];
let unmatched = 0;
let unlabelled = 0;

for (const row of elections) {
  const iso = isoByQid.get(row.country.value);
  if (!iso) {
    // A country with no ISO-3 code — historical or unrecognised. Counted, not
    // silently dropped.
    unmatched += 1;
    continue;
  }
  const label = row.eLabel?.value ?? '';

  /**
   * An unlabelled entity comes back as its own Q-id — "Q139270875" — which is
   * not an election name a reader can use, and rendering it would put a
   * database identifier on a public surface as though it were information.
   *
   * Dropped and COUNTED rather than shown, because the count is what tells a
   * future reader that the window had more elections than the list shows.
   */
  if (/^Q\d+$/.test(label) || label === '') {
    unlabelled += 1;
    continue;
  }

  const key = `${iso}|${row.date.value.slice(0, 10)}|${label}`;
  if (seen.has(key)) continue;
  seen.add(key);
  entries.push({ iso3: iso, date: row.date.value.slice(0, 10), name: label });
}

entries.sort((a, b) => a.date.localeCompare(b.date) || a.iso3.localeCompare(b.iso3));

const artefact = {
  $comment: [
    'GENERATED by scripts/generate-elections.mjs — do not hand-edit.',
    '',
    'A SCHEDULED date, not a promise. Elections are postponed, annulled and rescheduled, and a',
    'date in this file is what Wikidata recorded when it was generated — nothing here tracks',
    'whether an election actually happened.',
    '',
    'Regenerated periodically; a date in the past means the file is stale, and the panel says',
    'so rather than showing a fixture as a forecast.',
  ],
  generatedOn: FROM,
  windowTo: TO,
  unmatchedCountries: unmatched,
  /** Elections in the window whose entity has no English label. Dropped, not hidden. */
  unlabelledDropped: unlabelled,
  elections: entries,
};

writeFileSync(resolve(import.meta.dirname, '..', 'data', 'elections.json'), `${JSON.stringify(artefact, null, 2)}\n`);
console.log(`wrote ${entries.length} elections in ${FROM}..${TO} (${unmatched} without an ISO-3 country)`);
