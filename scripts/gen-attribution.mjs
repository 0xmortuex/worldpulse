#!/usr/bin/env node
/**
 * Regenerates the README attribution section from data/sources.json, so the
 * registry is the single place a licence or attribution string is edited.
 *
 * Rewrites everything between the ATTRIBUTION markers in README.md.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const START = '<!-- ATTRIBUTION:START -->';
const END = '<!-- ATTRIBUTION:END -->';

const CLASS_NOTE = {
  open: '',
  nc: ' **Non-commercial licence** — isolated behind its own adapter.',
  'share-alike': ' **Share-alike licence** — kept in a separate store, never merged into a general derived table.',
  restricted: ' **No reuse licence** — link-out only, not ingested.',
};

const registry = JSON.parse(await readFile(resolve(ROOT, 'data/sources.json'), 'utf8'));

const active = registry.sources.filter((source) => !source.excluded);
const excluded = registry.sources.filter((source) => source.excluded);

const lines = [
  START,
  '',
  '<!-- Generated by scripts/gen-attribution.mjs from data/sources.json. Do not edit by hand. -->',
  '',
  'worldpulse renders data from the following sources. Every figure in the UI carries',
  'its source, confidence tier and "as of" date; this list is the registry those come from.',
  '',
  '| Source | Panel | Licence | Attribution | Key |',
  '| --- | --- | --- | --- | --- |',
  ...active.map((source) => {
    const key = source.keyRequired ? `\`${source.keyEnv ?? 'required'}\`` : 'none';
    const licence = `${source.license}${CLASS_NOTE[source.licenseClass] ?? ''}`;
    return `| [${source.name}](${source.homepage}) | ${source.panel} | ${licence} | ${source.attribution ?? '—'} | ${key} |`;
  }),
  '',
  '### Considered and excluded',
  '',
  'These are named here because their absence is a deliberate licensing decision,',
  'not an oversight. Where a panel is missing data because of one of them, the panel',
  'says so rather than substituting a guess.',
  '',
  ...excluded.map((source) => `- **[${source.name}](${source.homepage})** — ${source.license}. ${source.notes ?? ''}`),
  '',
  END,
];

const readmePath = resolve(ROOT, 'README.md');
const readme = await readFile(readmePath, 'utf8');
const before = readme.indexOf(START);
const after = readme.indexOf(END);

if (before === -1 || after === -1) {
  console.error(`README.md is missing the ${START} / ${END} markers.`);
  process.exit(1);
}

const next = readme.slice(0, before) + lines.join('\n') + readme.slice(after + END.length);
await writeFile(readmePath, next);
console.log(`attribution section regenerated: ${active.length} active, ${excluded.length} excluded`);
